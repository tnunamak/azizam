@pytest.mark.parametrize("field", ["audio_rights", "transcript_rights", "provenance", "human_transcribed_evidence"])
def test_source_rights_and_provenance_are_required_and_nonempty(tmp_path, field):
    sample = _sample([_source("audio", b"a"), _source("transcript", b"t"), _source("segments", b"s")])
    for bad in (None, "", " "):
        changed = copy.deepcopy(sample)
        changed["sources"][0][field] = bad
        with pytest.raises(SampleError, match=field):
            _one(tmp_path, changed)
    changed = copy.deepcopy(sample)
    del changed["sources"][0][field]
    with pytest.raises(SampleError, match=field):
        _one(tmp_path, changed)
    if field.endswith("_rights"):
        for bad in ({"status": "approved", "note": "x"}, {"status": "stated", "note": " "}):
            changed = copy.deepcopy(sample)
            changed["sources"][0][field] = bad
            with pytest.raises(SampleError, match=field):
                _one(tmp_path, changed)



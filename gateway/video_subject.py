"""Subject selection for character replace (SCAIL-2 + SAM 3.1).

SCAIL-2 replaces the people that SAM 3 tracks in the driving video. With the
text prompt `person` SAM 3 tracks every person it finds, background people
included, so a clip with two men and a crowd gave a reference with one identity
and four tracked people. Targeting now works in three ways:

* default: replace the largest tracked person (index 0, tracks sorted by area at
  their first frame), and warn when more than one person was tracked;
* `subject_index`: pick another tracked person by that order;
* `source_point_x` / `source_point_y`: a point (0 to 1, from the top left) on the
  person in the first frame. SAM 3 segments that point and tracks only that person.

Picking the person is not enough. The reference character must also look like it
belongs where that person is, so `add_reference_fit` rescales and places it (see
there). Measured on a two-man clip: without it the model drew a large extra
woman next to the man and left him in place; with it she replaced him.

Nothing here talks to ComfyUI. The route applies these helpers to the graph.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any, Mapping

# The nodes of the graph this module edits are roles of the workflow's binding (``node_roles`` in the workflow's entry
# of the videos config), not constants: the graph file can change its node ids without a code change.
ROLE_KEYS = (
    "first_frame_node", "track_node", "color_mask_node", "probe_node", "point_detect_node", "sam_model_node",
    "reference_raw_node", "reference_text_node", "reference_detect_node", "reference_cropped_node", "fit_canvas_node",
)

# The ids `add_reference_fit` gives its own nodes, besides the fit canvas (a role). A role or a graph node must not use them.
_FRAGMENTS = json.loads(
    (Path(__file__).resolve().parent.parent / "registry/graph_fragments/video_reference_fit.json").read_text(encoding="utf-8")
)
FIT_IDS = tuple(node_id for node_id in _FRAGMENTS["fit"] if not node_id.startswith("${"))


def _fragment(name: str, values: Mapping[str, Any]) -> dict[str, Any]:
    """Instantiate ordered graph data without mutating the cached template."""
    def bind(value: Any) -> Any:
        if isinstance(value, str) and value.startswith("${") and value.endswith("}"):
            return values[value[2:-1]]
        if isinstance(value, dict):
            return {bind(key): bind(item) for key, item in value.items()}
        if isinstance(value, list):
            return [bind(item) for item in value]
        return value

    return bind(_FRAGMENTS[name])


_SCORES = re.compile(r"'scores':\s*\[([^\]]*)\]")


class SubjectError(ValueError):
    def __init__(self, message: str, param: str):
        super().__init__(message)
        self.param = param


class SubjectRoleError(ValueError):
    """The workflow's node roles do not fit its graph file: a template problem, found when the file loads."""


def check_roles(roles: Mapping[str, Any], graph: Mapping[str, Any]) -> None:
    """Refuse a subject-select workflow whose roles are missing, or name a node the graph file does not hold.

    ``point_detect_node`` and ``fit_canvas_node`` are ids for nodes that the edits add, so they must not be in the file.
    """
    missing = [key for key in ROLE_KEYS if not isinstance(roles.get(key), str)]
    size = roles.get("size_node")
    if missing or not (isinstance(size, list) and len(size) == 2):
        raise SubjectRoleError(f"subject select needs the node roles {sorted(missing) or ['size_node']}")
    added = {"point_detect_node", "fit_canvas_node"}
    if roles["point_detect_node"] == roles["fit_canvas_node"]:
        raise SubjectRoleError("point_detect_node and fit_canvas_node name the same node id (fit_canvas_node)")
    taken = sorted({*FIT_IDS} & ({*graph} | {roles[key] for key in added}))
    if taken:
        raise SubjectRoleError(f"node ids {taken} are generated by the reference fit, so the graph and the added roles must not use them")
    absent = [key for key in ROLE_KEYS if key not in added and roles[key] not in graph]
    clashing = [key for key in added if roles[key] in graph]
    if absent or clashing:
        raise SubjectRoleError(f"node roles {sorted(absent)} name no node of the graph; {sorted(clashing)} name one that exists")


def explicit_selection(block: Mapping[str, Any]) -> bool:
    """True when the caller chose the person (an index other than the default, or a point)."""
    index = str(block.get("subject_index", "")).strip()
    return ("source_point_x" in block) or (index not in ("", "0"))


def _point(block: Mapping[str, Any]) -> tuple[float, float] | None:
    """The selection point as fractions, or None when the request names no point."""
    has_x, has_y = "source_point_x" in block, "source_point_y" in block
    if has_x != has_y:
        raise SubjectError("source_point_x and source_point_y go together", "source_point_x")
    if not has_x:
        return None
    for name in ("source_point_x", "source_point_y"):
        value = block[name]
        if isinstance(value, bool) or not isinstance(value, (int, float)) or not 0.0 <= float(value) <= 1.0:
            raise SubjectError(f"{name} must be a number from 0 to 1", name)
    return float(block["source_point_x"]), float(block["source_point_y"])


def validate_selection(block: Mapping[str, Any]) -> None:
    """Check the request's person selection without touching a graph.

    The route calls this before it uploads the source video and the reference
    picture, so a selection it refuses leaves no files in the graph engine's
    input directory. `apply_point` reads the point through the same helper.
    """
    index_text = str(block.get("subject_index", "0")).strip()
    if not re.fullmatch(r"\d+(,\d+)*", index_text):
        raise SubjectError("subject_index must be a number like 0 or a list like 0,2", "subject_index")
    _point(block)


def apply_point(workflow: dict[str, Any], block: Mapping[str, Any], width: int, height: int,
                roles: Mapping[str, Any]) -> bool:
    """Rewire the graph to track only the person under a point. Return True if applied."""
    point = _point(block)
    if point is None:
        return False
    x = int(round(point[0] * (width - 1)))
    y = int(round(point[1] * (height - 1)))
    track_node, point_node, color_node = roles["track_node"], roles["point_detect_node"], roles["color_mask_node"]
    workflow.update(_fragment("point", {
        **roles, "positive_coords": json.dumps([{"x": x, "y": y}]),
    }))
    track = workflow[track_node]["inputs"]
    track.pop("conditioning", None)
    track["initial_mask"] = [point_node, 0]
    track["max_objects"] = 1
    workflow[color_node]["inputs"]["object_indices"] = "0"
    return True


def add_reference_fit(workflow: dict[str, Any], roles: Mapping[str, Any]) -> None:
    """Fit the reference character to the size and place of the person it replaces.

    SCAIL-2 reads the reference image as the character's look AND layout. The old
    graph centre-cropped the reference to the output frame, which cut the head and
    feet off a square portrait, and it left the character at whatever scale the
    image had. With other people in the clip the model then drew a large extra
    figure next to the person it should have replaced. This adds nodes that
    (1) cut the character out of the full reference with its SAM 3 mask, (2) scale it to the
    height of the selected person in the first frame, and (3) paste it at that
    person's position on a grey canvas of the output size. The fitted canvas then
    replaces the cropped reference for the CLIP vision features, the reference
    image and the reference mask.
    """
    g = workflow
    color, detect = roles["color_mask_node"], roles["reference_detect_node"]
    cropped, canvas_id = roles["reference_cropped_node"], roles["fit_canvas_node"]
    width_node, height_node = roles["size_node"]
    g.update(_fragment("fit", {
        **roles, "width_node": width_node, "height_node": height_node,
        "object_indices": g[color]["inputs"]["object_indices"],
        "sort_by": g[color]["inputs"]["sort_by"],
    }))
    # Use the fitted canvas wherever the cropped reference was used.
    canvas = [canvas_id, 0]
    for node in g.values():
        for key, value in node.get("inputs", {}).items():
            if value == [cropped, 0]:
                node["inputs"][key] = canvas
    g[detect]["inputs"]["image"] = canvas


def tracked_count(history_outputs: Mapping[str, Any] | None, probe_node: str) -> int | None:
    """Number of tracked people, read from the probe node's text (a repr of the
    SAM 3 track data that ends with one score per tracked object). ``probe_node`` is the workflow's role."""
    node = (history_outputs or {}).get(probe_node)
    texts = node.get("text") if isinstance(node, Mapping) else None
    if not texts:
        return None
    match = _SCORES.search(str(texts[0]))
    if not match:
        return None
    return len([part for part in match.group(1).split(",") if part.strip()])


def warnings_for(count: int | None, *, explicit: bool, subject: str) -> list[str]:
    if count is None:
        return []
    if count == 0:
        return [f"No person matching '{subject}' was found in the source video; the result may show no replacement. "
                "Try source_subject 'person', or source_point_x/source_point_y."]
    if count > 1 and not explicit:
        return [f"{count} people matched '{subject}' in the source video (background people count). "
                "Only the largest one (subject_index 0) was replaced. To pick another, set "
                "extensions.com.azizam.workflow.subject_index (0 = largest at first appearance, 1 = next, ...) or "
                "source_point_x/source_point_y (0 to 1, a point on the person in the first frame)."]
    return []

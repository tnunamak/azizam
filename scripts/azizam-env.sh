azizam_read_env() {
  local azizam_name=$1 azizam_old_name
  shift
  [[ ${!azizam_name+present} ]] && return 0
  for azizam_old_name in "$@"; do
    if [[ ${!azizam_old_name+present} ]]; then
      export "$azizam_name=${!azizam_old_name}"
      return 0
    fi
  done
  return 0
}

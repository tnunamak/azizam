#!/usr/bin/env python3
"""Vendor the @vivid-fish/brand CSS into the gateway as a Python module.

The gateway is a pure-Python, server-rendered app with no JS build step, so it
can't ``@import "@vivid-fish/brand"`` the way a Tailwind consumer would. Instead
we vendor the package's design tokens and component classes into
``gateway/brand_css.py`` as plain CSS strings, recording the exact source commit
so drift between the gateway and the upstream brand package stays visible.

The brand package is the single source of truth for the visual language. Do NOT
hand-edit ``gateway/brand_css.py`` — change the brand package
(``~/code/vivid-fish-brand``), pull it, and re-run this script:

    python3 scripts/vendor_brand_css.py

What it does:
  * reads ``src/tokens.css`` (the ``:root`` custom properties) verbatim
  * reads ``src/components.css`` and unwraps its ``@layer components { ... }``
    wrapper — a plain ``<style>`` element has no Tailwind layers, and unlayered
    rules would otherwise always beat layered ones, so we flatten the brand
    components into the normal cascade where the gateway's own chrome can layer
    on top in source order.

``theme.css`` (Tailwind ``@theme``, inert without Tailwind) and
``animations.css`` (glow/pulse keyframes the gateway doesn't use) are
intentionally not vendored.
"""

from __future__ import annotations

import re
import subprocess
import textwrap
from pathlib import Path

# The brand package checkout. Override with VF_BRAND_DIR if it lives elsewhere.
import os

BRAND_DIR = Path(
    os.environ.get("VF_BRAND_DIR", str(Path.home() / "code" / "vivid-fish-brand"))
)
OUT = Path(__file__).resolve().parent.parent / "gateway" / "brand_css.py"


def _strip_leading_banner(css: str) -> str:
    """Drop a single leading ``/* ... */`` file banner comment."""
    return re.sub(r"^\s*/\*.*?\*/\s*", "", css, count=1, flags=re.S)


def _drop_legacy_dive_aliases(css: str) -> str:
    """Strip the backward-compatible ``--dive-*`` alias declarations.

    The brand package keeps these for OLDER consumers that predate the
    ``--vf-*`` rename; the gateway is a new consumer that uses only ``--vf-*``
    (and its own ``--panel`` / ``--line`` shell aliases), so shipping ~15 unused
    ``--dive-*`` custom properties on every page is dead weight. The gateway
    also asserts no legacy palette leaks into served HTML. Drop each
    ``--dive-...: ...;`` line and the lone comment that introduces them.
    """
    out = []
    for line in css.splitlines():
        stripped = line.strip()
        if stripped.startswith("--dive-"):
            continue
        if "Backward-compatible habitat aliases" in stripped:
            continue
        out.append(line)
    # Collapse any blank line left where the block used to be.
    text = "\n".join(out)
    return re.sub(r"\n[ \t]*\n[ \t]*\n", "\n\n", text)


def _unwrap_layer(css: str) -> str:
    """Remove the outer ``@layer components { ... }`` wrapper and de-indent."""
    body = _strip_leading_banner(css).strip()
    if not body.startswith("@layer components"):
        raise SystemExit(
            "components.css no longer starts with '@layer components' — "
            "update scripts/vendor_brand_css.py to match the new structure."
        )
    body = body[body.index("{") + 1 :].rstrip()
    if not body.endswith("}"):
        raise SystemExit("Unbalanced @layer wrapper in components.css.")
    body = body[:-1].rstrip()
    # The @layer body is indented two spaces; de-indent the top level so the
    # vendored CSS reads naturally. Nested blocks keep their relative indent.
    lines = [ln[2:] if ln.startswith("  ") else ln for ln in body.splitlines()]
    return textwrap.dedent("\n".join(lines)).strip()


def main() -> None:
    tokens_src = (BRAND_DIR / "src" / "tokens.css").read_text()
    comps_src = (BRAND_DIR / "src" / "components.css").read_text()

    sha = subprocess.check_output(
        ["git", "-C", str(BRAND_DIR), "rev-parse", "HEAD"]
    ).decode().strip()
    try:
        version = subprocess.check_output(
            ["node", "-e", "process.stdout.write(require('./package.json').version)"],
            cwd=str(BRAND_DIR),
        ).decode().strip()
    except Exception:
        # node may be unavailable; fall back to a grep.
        pkg = (BRAND_DIR / "package.json").read_text()
        m = re.search(r'"version"\s*:\s*"([^"]+)"', pkg)
        version = m.group(1) if m else "unknown"

    tokens_body = _drop_legacy_dive_aliases(
        _strip_leading_banner(tokens_src)
    ).strip()
    comps_body = _unwrap_layer(comps_src)

    out = f'''"""Vendored @vivid-fish/brand CSS — DO NOT EDIT BY HAND.

Generated by ``scripts/vendor_brand_css.py`` from the brand package, which is the
single source of truth for the gateway's visual language. To change tokens or
component classes, edit ``~/code/vivid-fish-brand`` and re-run the script.

    source:  @vivid-fish/brand v{version}
    commit:  {sha}
    repo:    github.com/Vivid-Fish/vivid-fish-brand

``BRAND_TOKENS_CSS`` is ``src/tokens.css`` verbatim (the ``:root`` custom
properties). ``BRAND_COMPONENTS_CSS`` is ``src/components.css`` with its
``@layer components`` wrapper removed so the classes sit in the normal cascade
(a plain ``<style>`` has no Tailwind layers). The gateway composes these ahead
of its own chrome in ``gateway_shell.SHELL_CSS``.
"""

from __future__ import annotations

__all__ = ["BRAND_TOKENS_CSS", "BRAND_COMPONENTS_CSS", "BRAND_SOURCE_COMMIT"]

BRAND_SOURCE_COMMIT = "{sha}"

BRAND_TOKENS_CSS = r"""
{tokens_body}
"""

BRAND_COMPONENTS_CSS = r"""
{comps_body}
"""
'''

    OUT.write_text(out)
    print(f"Wrote {OUT.relative_to(Path.cwd())}")
    print(f"  brand v{version} @ {sha[:9]}")
    print(f"  tokens: {len(tokens_body)} chars, components: {len(comps_body)} chars")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Generate TypeScript from the portable Python response contracts."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys
import types
from typing import Literal, Union, get_args, get_origin, get_type_hints
from typing_extensions import NotRequired, Required, is_typeddict

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from gateway import product_contracts as contracts

OUTPUT = ROOT / "web/src/lib/product-api-types.ts"


def ts_type(annotation):
    origin, args = get_origin(annotation), get_args(annotation)
    if origin in (Required, NotRequired):
        return ts_type(args[0])
    if origin in (Union, types.UnionType):
        return " | ".join(ts_type(item) for item in args)
    if origin is Literal:
        return " | ".join(json.dumps(item) for item in args)
    if origin is list:
        return f"Array<{ts_type(args[0])}>"
    if origin is dict:
        if args[0] is not str:
            raise TypeError("JSON object keys must be strings")
        return f"Record<string, {ts_type(args[1])}>"
    if is_typeddict(annotation):
        return annotation.__name__
    scalars = {str: "string", int: "number", float: "number", bool: "boolean",
               type(None): "null", object: "unknown"}
    if annotation in scalars:
        return scalars[annotation]
    raise TypeError(f"Unsupported contract annotation: {annotation!r}")


def render():
    lines = ["// Generated by scripts/generate-product-api-types.py. Do not edit.",
             "// Source: gateway/product_contracts.py. Run the generator with --check in CI.", ""]
    for name, definition in vars(contracts).items():
        if name.startswith("_"):
            continue
        if get_origin(definition) is Literal:
            lines.extend([f"export type {name} = {ts_type(definition)};", ""])
        elif is_typeddict(definition):
            lines.append(f"export interface {name} {{")
            for field, annotation in get_type_hints(definition, include_extras=True).items():
                optional = "?" if field in definition.__optional_keys__ else ""
                lines.append(f"  {field}{optional}: {ts_type(annotation)};")
            lines.extend(["}", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            print("Product API types are stale; run scripts/generate-product-api-types.py", file=sys.stderr)
            return 1
    else:
        OUTPUT.write_text(generated)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

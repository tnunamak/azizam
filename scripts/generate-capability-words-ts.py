#!/usr/bin/env python3
"""Generate member-facing TypeScript words from validated capability data."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from gateway.capability_ids import CAPABILITY_LABELS, load_capability_member_words, load_capability_screen_words

OUTPUT = ROOT / "web/src/lib/capability-words.ts"


def render():
    member_labels, task_names = load_capability_member_words()
    models_explainers, try_help, request_nouns = load_capability_screen_words()
    lines = ["// Generated by scripts/generate-capability-words-ts.py. Do not edit.",
             "// Source: registry/capability_words.yml. Run the generator with --check in CI.", ""]
    for name, words in (("capabilityLabels", CAPABILITY_LABELS),
                        ("capabilityTaskNames", task_names),
                        ("capabilityMemberLabels", member_labels),
                        ("capabilityModelsExplainers", models_explainers),
                        ("capabilityTryHelp", try_help),
                        ("capabilityRequestNouns", request_nouns)):
        lines.append(f"export const {name} = {{")
        for capability, word in words.items():
            lines.append(f"  {json.dumps(capability)}: {json.dumps(word)},")
        lines.extend(["} as const;", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            print("Capability words are stale; run scripts/generate-capability-words-ts.py", file=sys.stderr)
            return 1
    else:
        OUTPUT.write_text(generated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
